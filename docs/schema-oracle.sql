-- ============================================================
-- gps_demo1 Oracle 建表脚本
-- 目标库：Oracle Database 11g Enterprise Edition 11.2.0.1.0
--
-- 11g 不支持 IDENTITY，主键用 SEQUENCE + TRIGGER 生成。
-- 只创建对象，不删除、不修改已有数据。
-- 重复执行前请先确认表是否已存在，必要时备份。
-- ============================================================

-- 终端设备
CREATE TABLE GPS_DEVICE (
    PHONE        VARCHAR2(20 CHAR) NOT NULL,
    AUTH_CODE    VARCHAR2(64 CHAR) NOT NULL,
    MAKER        VARCHAR2(16 CHAR),
    MODEL        VARCHAR2(32 CHAR),
    TERMINAL_ID  VARCHAR2(16 CHAR),
    PLATE        VARCHAR2(32 CHAR),
    PLATE_COLOR  NUMBER(2),
    ONLINE_FLAG       NUMBER(1) DEFAULT 0 NOT NULL,
    LAST_SEEN    TIMESTAMP,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GPS_DEVICE PRIMARY KEY (PHONE)
);

COMMENT ON TABLE GPS_DEVICE IS '终端设备';
COMMENT ON COLUMN GPS_DEVICE.PHONE IS '终端手机号，11 位';
COMMENT ON COLUMN GPS_DEVICE.AUTH_CODE IS '鉴权码';
COMMENT ON COLUMN GPS_DEVICE.PLATE IS '车牌';
COMMENT ON COLUMN GPS_DEVICE.ONLINE_FLAG IS '0 离线，1 在线';

-- 轨迹
CREATE TABLE GPS_LOCATION (
    ID           NUMBER(19) NOT NULL,
    PHONE        VARCHAR2(20 CHAR) NOT NULL,
    DEVICE_TIME  TIMESTAMP NOT NULL,
    LAT          NUMBER(10,6) NOT NULL,
    LNG          NUMBER(10,6) NOT NULL,
    SPEED_KMH    NUMBER(5,1),
    DIRECTION    NUMBER(3),
    ALTITUDE     NUMBER(6),
    ACC_ON       NUMBER(1),
    ARMED        NUMBER(1),
    VALID_FIX    NUMBER(1),
    ALARM_FLAG   NUMBER(19),
    STATUS       NUMBER(19),
    EXTRAS_JSON  VARCHAR2(4000 CHAR),
    RAW_HEX      VARCHAR2(4000 CHAR),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GPS_LOCATION PRIMARY KEY (ID)
);

CREATE SEQUENCE SEQ_GPS_LOCATION
    START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;

CREATE OR REPLACE TRIGGER TRG_GPS_LOCATION_ID
BEFORE INSERT ON GPS_LOCATION
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT SEQ_GPS_LOCATION.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

CREATE UNIQUE INDEX UK_GPS_LOCATION_POS
    ON GPS_LOCATION (PHONE, DEVICE_TIME, LAT, LNG);

CREATE INDEX IDX_GPS_LOCATION_PHONE_TIME
    ON GPS_LOCATION (PHONE, DEVICE_TIME);

COMMENT ON TABLE GPS_LOCATION IS '终端位置轨迹';
COMMENT ON COLUMN GPS_LOCATION.DEVICE_TIME IS '设备时间，北京时间';
COMMENT ON COLUMN GPS_LOCATION.LAT IS '纬度，单位度';
COMMENT ON COLUMN GPS_LOCATION.LNG IS '经度，单位度';
COMMENT ON COLUMN GPS_LOCATION.SPEED_KMH IS '速度，km/h';
COMMENT ON COLUMN GPS_LOCATION.EXTRAS_JSON IS 'TLV 附加信息，简化 JSON';
COMMENT ON COLUMN GPS_LOCATION.RAW_HEX IS '原始帧十六进制，排障用';

-- 报警
CREATE TABLE GPS_ALARM (
    ID           NUMBER(19) NOT NULL,
    PHONE        VARCHAR2(20 CHAR) NOT NULL,
    ALARM_TYPE   VARCHAR2(32 CHAR) NOT NULL,
    ALARM_LEVEL  NUMBER(2),
    DISTANCE_M   NUMBER(8,1),
    LAT          NUMBER(10,6),
    LNG          NUMBER(10,6),
    DEVICE_TIME  TIMESTAMP,
    MESSAGE      VARCHAR2(500 CHAR),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_GPS_ALARM PRIMARY KEY (ID)
);

CREATE SEQUENCE SEQ_GPS_ALARM
    START WITH 1 INCREMENT BY 1 CACHE 20 NOCYCLE;

CREATE OR REPLACE TRIGGER TRG_GPS_ALARM_ID
BEFORE INSERT ON GPS_ALARM
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
    SELECT SEQ_GPS_ALARM.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

CREATE INDEX IDX_GPS_ALARM_PHONE_TIME
    ON GPS_ALARM (PHONE, CREATED_AT);

COMMENT ON TABLE GPS_ALARM IS '200 米偏移报警事件';
COMMENT ON COLUMN GPS_ALARM.ALARM_TYPE IS 'DEVIATION_RAISED/ESCALATED/CLEARED';
COMMENT ON COLUMN GPS_ALARM.DISTANCE_M IS '距参考点距离，米';

-- ============================================================
-- 说明：
-- 1. 11g 不支持 GENERATED ALWAYS AS IDENTITY，所以用 sequence + trigger。
-- 2. trigger 里的 WHEN (NEW.ID IS NULL) 不写冒号；body 里写 :NEW.ID。
-- 3. 如果以后升级到 12c+，可以改成 IDENTITY，但当前 11g 不要用。
-- ============================================================
